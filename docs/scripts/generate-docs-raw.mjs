#!/usr/bin/env node
// Reads every app/content/docs/**/*.mdx file and emits a typed TS module
// exporting their raw source as a string map. We do this at build time because
// the @mdx-js/rollup plugin transforms .mdx files regardless of `?raw` query,
// so `import.meta.glob('**/*.mdx', { query: '?raw' })` doesn't actually return
// strings — it returns transformed module objects.
//
// Runs as `predev` and `prebuild`.

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const docsDir = resolve(__dirname, "..", "app", "content", "docs");
const outFile = resolve(__dirname, "..", "app", "lib", "docs-raw-data.ts");

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      out.push(...walk(full));
    } else if (entry.endsWith(".mdx")) {
      out.push(full);
    }
  }
  return out;
}

function pathToSlug(full) {
  return relative(docsDir, full).replace(/\\/g, "/").replace(/\.mdx$/, "");
}

const files = walk(docsDir);
const entries = files
  .map((f) => ({ slug: pathToSlug(f), raw: readFileSync(f, "utf-8") }))
  .sort((a, b) => a.slug.localeCompare(b.slug));

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generate-docs-raw.mjs — do not edit by hand.");
lines.push("// Re-run via `npm run sync-docs-raw` (also runs in predev / prebuild).");
lines.push("");
lines.push("export const RAW_DOCS: Record<string, string> = {");
for (const { slug, raw } of entries) {
  lines.push(`  ${JSON.stringify(slug)}: ${JSON.stringify(raw)},`);
}
lines.push("};");
lines.push("");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), "utf-8");

console.log(`[generate-docs-raw] wrote ${entries.length} docs → ${relative(process.cwd(), outFile)}`);
